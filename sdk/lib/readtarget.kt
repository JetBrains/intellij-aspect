package com.intellij.aspect.lib

import com.google.devtools.intellij.ideinfo.IntellijIdeInfo.CToolchainIdeInfo.XcodeInfo
import com.google.devtools.intellij.ideinfo.IntellijIdeInfo.TargetIdeInfo
import com.google.protobuf.Message
import com.google.protobuf.TextFormat
import java.io.IOException
import java.nio.file.Path
import kotlin.io.path.readBytes

private val PARSER by lazy {
  TextFormat.Parser
    .newBuilder()
    .setAllowUnknownFields(true)
    .build()
}

// Read a textproto message generated by this aspect from a file
fun readTargetFromFile(file: Path, logErrorMessage: (String?) -> Unit = {}): TargetIdeInfo? {
  val builder = TargetIdeInfo.newBuilder()

  try {
    readMessageFromFile(file, builder)
  } catch (e: IOException) {
    logErrorMessage(e.message)
    return null
  }

  return builder.build()
}

// Read an XcodeInfo textproto referenced by CToolchainIdeInfo.xcode_info from a file
fun readXcodeInfoFromFile(file: Path, logErrorMessage: (String?) -> Unit = {}): XcodeInfo? {
  val builder = XcodeInfo.newBuilder()

  try {
    readMessageFromFile(file, builder)
  } catch (e: IOException) {
    logErrorMessage(e.message)
    return null
  }

  return builder.build()
}

// keep private: jar_jar does not relocate protobuf types in the Kotlin metadata of public declarations
@Throws(IOException::class)
private fun readMessageFromFile(file: Path, builder: Message.Builder) {
  try {
    PARSER.merge(file.readBytes().toString(Charsets.UTF_8), builder)
  } catch (e: TextFormat.ParseException) {
    throw IOException("invalid textproto message", e)
  }
}
