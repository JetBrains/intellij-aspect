package com.intellij.aspect.lib

import com.google.devtools.intellij.aspect.Aspect.AspectConfiguration
import com.google.devtools.intellij.aspect.Aspect.Module
import com.intellij.aspect.private.lib.utils.asBazelPath
import com.intellij.aspect.private.lib.utils.parseTextProto
import java.io.IOException
import java.nio.file.Path

private const val DEFAULT_ASPECT_NAME = "intellij_aspect"

/**
 * Describes how an aspect can be configured, derived from an [AspectConfiguration] message as
 * generated by `//private/rules:aspect_config.bzl`.
 */
class AspectDefinition private constructor(val proto: AspectConfiguration) {

  data class Location(val file: Path, val name: String) {
    init {
      require(!file.isAbsolute) { "aspect file must be relative: $file" }
    }

    override fun toString(): String {
      val label = when (val parent = file.parent) {
        null -> ":${file.fileName}"
        else -> "${asBazelPath(parent)}:${file.fileName}"
      }

      return "$label%$name"
    }
  }

  /**
   * The location of the aspect once deployed.
   */
  val location: Location = Location(
    file = Path.of(proto.file),
    name = proto.name.ifEmpty { DEFAULT_ASPECT_NAME },
  )

  /**
   * All modules known to this aspect configuration.
   */
  val modules: List<Module>
    get() = proto.modulesList

  /**
   * All modules that will be enabled for the rule set.
   */
  fun modulesFor(rulesets: Iterable<Rules>): List<Module> {
    val names = rulesets.mapTo(mutableSetOf()) { it.name }
    return modules.filter { module -> module.rulesetsList.isEmpty() || module.rulesetsList.any { it in names } }
  }

  /**
   * Generates the content of the aspect file for a deployment to [relativeDestination]
   * inside a workspace, enabling only the modules required for the given rule sets.
   */
  fun generateAspectFile(relativeDestination: Path, rulesets: Iterable<Rules>): String {
    val modules = modulesFor(rulesets)
    val prefix = asBazelPath(relativeDestination)

    val files = modules.joinToString(", ") { it.file }
    val loads = modules.map { it.file }.joinToString("\n") { """load("//$prefix/modules:$it.bzl", $it = "module")""" }

    return """
# generated by //sdk/lib/AspectDefinition.kt - do not edit

load("//$prefix/intellij:aspect.bzl", "intellij_configure_aspect")
$loads

MODULES = [$files]

${location.name} = intellij_configure_aspect(
    modules = MODULES,
    container = "//$prefix/config:module_container",
)
"""
  }

  companion object {

    /**
     * Reads an aspect definition bundled as a resource of this jar.
     */
    @Throws(IOException::class)
    internal fun fromResource(name: String): AspectDefinition {
      val stream = AspectDefinition::class.java.getResourceAsStream(name)
        ?: throw IOException("bundled aspect definition not found: $name")

      val proto = stream.use {
        parseTextProto<AspectConfiguration>(it.reader(Charsets.UTF_8).readText())
      }

      return AspectDefinition(proto)
    }
  }
}
