package com.intellij.aspect.lib

import com.google.devtools.intellij.aspect.Aspect.Module
import com.intellij.aspect.private.lib.utils.asBazelPath
import java.io.IOException
import java.nio.file.Files
import java.nio.file.Path
import java.util.Locale

data class AspectConfig(
  /**
   * The Bazel version written into the config file.
   */
  val bazelVersion: String,
  /**
   * A mapping from default repo names to a specific replacement e.g., canonical repo name.
   */
  val repoMapping: Map<Rules, String>,
  /**
   * Languages for which to use the builtin rule, i.e., for which to strip rule set loads.
   */
  val useBuiltin: Set<Rules>,
  /**
   * Rule sets for which information will be requested when running the aspect. If null, take
   * all Rules mentioned in the repoMapping or useBuiltin.
   */
  val rulesets: Set<Rules>? = null,
  /**
   * Attributes the aspect should walk. If null, take the default of walking all attributes.
   */
  val attrAspects: List<String>? = null,
  /**
   * Whether the aspect should reduce no-ide targets to tomb stones (and, in particular, not provide
   * any information for targets only reachable through no-ide targets).
   */
  val dropNoIde: Boolean = false,
)

/**
 * Creates the config directory and writes the config file as well as the
 * required BUILD file and the files of all bundled aspects.
 */
@Throws(IOException::class)
internal fun writeAspectConfig(destination: Path, relativeDestination: Path, config: AspectConfig) {
  val directory = destination.resolve("config")
  Files.createDirectories(directory)

  val buildFile = directory.resolve("BUILD")
  writeFileIfContentDiffers(buildFile, generateBuildFile(relativeDestination))

  val configFile = directory.resolve("config.bzl")
  writeFileIfContentDiffers(configFile, generateConfigStruct(config))

  val rulesets = config.rulesets ?: (config.useBuiltin + config.repoMapping.keys)

  for (aspect in listOf(INTELLIJ_ASPECT, INTELLIJ_CC_DEBUG_ASPECT)) {
    writeFileIfContentDiffers(
      path = destination.resolve(aspect.location.file),
      payload = aspect.generateAspectFile(relativeDestination, rulesets, config.attrAspects, config.dropNoIde),
    )
  }
}

private fun generateBuildFile(relativeDestination: Path): String {
  val prefix = asBazelPath(relativeDestination)

  return """
# generated by //sdk/lib/config.kt - do not edit

load("//$prefix/modules:module.bzl", "intellij_module")

intellij_module.container(
    name = "module_container",
    visibility = ["//visibility:public"],
)
    """.trimIndent()
}

private fun generateConfigStruct(config: AspectConfig) = """
# generated by //sdk/lib/config.kt - do not edit

config = struct(
  bazel_version = "${config.bazelVersion}",
  os = "${System.getProperty("os.name").lowercase(Locale.ROOT)}",
)
"""

/**
 * Generates the content of the aspect file for a deployment to [relativeDestination]
 * inside a workspace, enabling only the modules required for the given rule sets. If
 * [attrAspects] is null, the aspect walks all attributes.
 */
internal fun AspectDefinition.generateAspectFile(
  relativeDestination: Path,
  rulesets: Iterable<Rules>,
  attrAspects: List<String>? = null,
  dropNoIde: Boolean = false,
): String {
  val modules = modulesFor(rulesets)
  val prefix = asBazelPath(relativeDestination)

  val loads = modules.joinToString("\n") { encodeLoad(prefix, it) }

  val attrs = mutableMapOf<String, String>()
  attrs["modules"] = encodeList(modules.map { it.file })
  attrs["container"] = encodeString("//$prefix/config:module_container")

  if (attrAspects != null) {
    attrs["attr_aspects"] = encodeList(attrAspects.map(::encodeString))
  }
  if (dropNoIde) {
    attrs["drop_no_ide"] = "True"
  }

  return """
# generated by //sdk/lib/config.kt - do not edit

load("//$prefix/intellij:aspect.bzl", "intellij_configure_aspect")
$loads

${location.name} = intellij_configure_aspect(
${encodeAttrs(attrs)}
)
"""
}

private fun encodeLoad(prefix: String, module: Module): String {
  val file = module.file
  return """load("//$prefix/modules:$file.bzl", $file = "module")"""
}

private fun encodeString(value: String): String {
  return "\"$value\""
}

private fun encodeList(elements: List<String>): String {
  return elements.joinToString(", ", prefix = "[", postfix = "]")
}

private fun encodeAttrs(attrs: Map<String, String>): String {
  return attrs.entries.joinToString("\n") { (key, value) -> "    $key = $value," }
}
