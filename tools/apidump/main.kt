private const val HEADER = """# Public API of the sdk, generated by //tools/apidump - do not edit
# Every change to this file is an API change. Review it and update the fixture with:
#
#   bazel build //testing/tests/sdk:api_dump
#   install -m 644 bazel-bin/testing/tests/sdk/api_dump.txt testing/tests/sdk/api.txt
"""

/**
 * Dumps all public and protected symbols of a set of jars, excluding Kotlin internal declarations.
 */
fun main(args: Array<String>) {
  val parser = ArgParser("apidump")

  val jars by parser.option(
    ArgType.String,
    fullName = "jar",
    description = "Jar whose classes are part of the API",
  ).required().multiple()

  val classpath by parser.option(
    ArgType.String,
    fullName = "classpath",
    description = "Additional jar required to load the API classes",
  ).multiple()

  val excludes by parser.option(
    ArgType.String,
    fullName = "exclude",
    description = "Package to leave out of the dump, including its sub packages",
  ).multiple()

  val output by parser.option(
    ArgType.String,
    fullName = "output",
    description = "File to write the dump to, stdout if absent",
  )

  parser.parse(args)

  val dump = dumpApi(
    jars = jars.map(Path::of),
    classpath = classpath.map(Path::of),
    excludes = excludes.map { it.trimEnd('.') + "." },
  )

  when (val output = output?.let(Path::of)) {
    null -> print(dump)
    else -> Files.writeString(output, dump, StandardCharsets.UTF_8)
  }
}

private fun dumpApi(jars: List<Path>, classpath: List<Path>, excludes: List<String>): String {
  val names = jars.flatMap(::listClasses).filter { name -> excludes.none(name::startsWith) }.sorted()

  // the parent loader provides the kotlin stdlib in case it is missing from the classpath
  val urls = (jars + classpath).map { it.toUri().toURL() }.toTypedArray()
  val loader = URLClassLoader(urls, ApiDump::class.java.classLoader)

  return buildString {
    append(HEADER)

    for (name in names) {
      val clazz = try {
        Class.forName(name, false, loader)
      } catch (e: Throwable) {
        throw IllegalStateException("could not load $name", e)
      }

      if (!isExported(clazz)) continue

      val members = describeMembers(clazz)

      // Kotlin file facades without exported declarations are not part of the API
      if (members.isEmpty() && readKotlinMetadata<KotlinClassMetadata.FileFacade>(clazz) != null) continue

      append("\n")
      append(describeClass(clazz)).append("\n")
      members.sorted().forEach { append("  ").append(it).append("\n") }
    }
  }
}

private fun listClasses(jar: Path): List<String> {
  return ZipFile(jar.toFile()).use { zip ->
    zip.entries().asSequence()
      .map { it.name }
      .filter { it.endsWith(".class") && !it.startsWith("META-INF/") && !it.endsWith("module-info.class") }
      .map { it.removeSuffix(".class").replace('/', '.') }
      .toList()
  }
}

private fun isExported(clazz: Class<*>): Boolean {
  if (clazz.isSynthetic || clazz.isAnonymousClass || clazz.isLocalClass) return false
  if (!isExported(clazz.modifiers) || isKotlinInternal(clazz)) return false

  // nested classes are only reachable if their enclosing class is reachable
  return clazz.enclosingClass?.let(::isExported) ?: true
}

private fun isExported(modifiers: Int): Boolean {
  return Modifier.isPublic(modifiers) || Modifier.isProtected(modifiers)
}

private fun describeClass(clazz: Class<*>): String {
  val builder = StringBuilder(clazz.toGenericString())

  val superclass = clazz.genericSuperclass
  if (superclass != null && superclass != Any::class.java) {
    builder.append(" extends ").append(superclass.typeName)
  }

  val interfaces = clazz.genericInterfaces
  if (interfaces.isNotEmpty()) {
    builder.append(" implements ").append(interfaces.joinToString(", ") { it.typeName })
  }

  return builder.toString()
}

private fun describeMembers(clazz: Class<*>): List<String> {
  val internalMembers = kotlinInternalMembers(clazz)

  val members = sequence<Member> {
    yieldAll(clazz.declaredConstructors.asSequence())
    yieldAll(clazz.declaredFields.asSequence())
    yieldAll(clazz.declaredMethods.asSequence().filter { !it.isBridge })
  }

  return members
    .filter { !it.isSynthetic && isExported(it.modifiers) }
    .filter { signatureOf(it) !in internalMembers }
    // the field holding a companion object has the visibility of the companion object
    .filter { it !is Field || it.type.declaringClass != clazz || isExported(it.type) }
    .map { describeMember(clazz, it) }
    .toList()
}

private fun describeMember(clazz: Class<*>, member: Member): String {
  val description = when (member) {
    is Constructor<*> -> member.toGenericString()
    is Method -> member.toGenericString()
    is Field -> member.toGenericString()
    else -> member.toString()
  }

  // strip the redundant declaring class prefix from the member name
  return description.replace("${clazz.name}.", "")
}

/**
 * Kotlin compiles internal declarations to public bytecode, only the Kotlin metadata knows
 * their actual visibility.
 */
private inline fun <reified T : KotlinClassMetadata> readKotlinMetadata(clazz: Class<*>): T? {
  return clazz.getAnnotation(Metadata::class.java)
    ?.let(KotlinClassMetadata::readLenient)
    as? T
}

private fun isKotlinInternal(clazz: Class<*>): Boolean {
  val metadata = readKotlinMetadata<KotlinClassMetadata.Class>(clazz) ?: return false
  return !isExported(metadata.kmClass.visibility)
}

private fun kotlinInternalMembers(container: KmDeclarationContainer): Set<JvmMemberSignature?> {
  val signatures = mutableSetOf<JvmMemberSignature?>()

  container.functions
    .filter { !isExported(it.visibility) }
    .mapTo(signatures) { it.signature }

  container.properties
    .filter { !isExported(it.visibility) }
    .mapTo(signatures) { it.getterSignature }

  return signatures
}

private fun kotlinInternalMembers(clazz: Class<*>): Set<String> {
  val signatures = mutableSetOf<JvmMemberSignature?>()

  readKotlinMetadata<KotlinClassMetadata.Class>(clazz)?.let { metadata ->
    metadata.kmClass.constructors
      .filter { !isExported(it.visibility) }
      .mapTo(signatures) { it.signature }

    signatures.addAll(kotlinInternalMembers(metadata.kmClass))
  }

  readKotlinMetadata<KotlinClassMetadata.FileFacade>(clazz)?.let { metadata ->
    signatures.addAll(kotlinInternalMembers(metadata.kmPackage))
  }

  return signatures.filterNotNull().map(::signatureOf).toSet()
}

private fun isExported(visibility: Visibility): Boolean {
  return visibility == Visibility.PUBLIC || visibility == Visibility.PROTECTED
}

private fun signatureOf(signature: JvmMemberSignature): String = when (signature) {
  is JvmMethodSignature -> signature.name + signature.descriptor
  is JvmFieldSignature -> signature.name + ":" + signature.descriptor
}

private fun signatureOf(member: Member): String = when (member) {
  is Constructor<*> -> "<init>" + MethodType.methodType(Void.TYPE, member.parameterTypes).toMethodDescriptorString()
  is Method -> member.name + MethodType.methodType(member.returnType, member.parameterTypes).toMethodDescriptorString()
  is Field -> member.name + ":" + member.type.descriptorString()
  else -> member.name
}

